const getLifePathFromAnyDobFormat = (dob: string): number => {
  if (!dob) return 0;
  try {
    let parts: string[] = [];
    if (dob.includes('-')) {
      parts = dob.split('-');
    } else if (dob.includes('/')) {
      parts = dob.split('/');
    }
    if (parts.length === 3) {
      if (parts[0].length === 4) {
        const y = Number(parts[0]);
        const m = Number(parts[1]);
        const d = Number(parts[2]);
        return calculateLifePath(`${String(d).padStart(2, '0')}/${String(m).padStart(2, '0')}/${y}`);
      } else {
        return calculateLifePath(dob);
      }
    }
  } catch (err) {
    console.error('getLifePathFromAnyDobFormat error', err);
  }
  return 1;
};

const getMulankFromAnyDobFormat = (dob: string): number => {
  if (!dob) return 0;
  try {
    let parts: string[] = [];
    if (dob.includes('-')) {
      parts = dob.split('-');
    } else if (dob.includes('/')) {
      parts = dob.split('/');
    }
    if (parts.length === 3) {
      let d = 1;
      if (parts[0].length === 4) {
        d = Number(parts[2]);
      } else {
        d = Number(parts[0]);
      }
      if (d === 11 || d === 22) return d;
      return reduceToSingleDigit(d, false);
    }
  } catch (err) {
    console.error('getMulankFromAnyDobFormat error', err);
  }
  return 1;
};

const calculatePersonalYearForYear = (dob: string, year: number): number => {
  try {
    let day = 1, month = 1;
    let parts: string[] = [];
    if (dob.includes('-')) {
      parts = dob.split('-');
      if (parts[0].length === 4) {
        day = Number(parts[2]);
        month = Number(parts[1]);
      } else {
        day = Number(parts[0]);
        month = Number(parts[1]);
      }
    } else if (dob.includes('/')) {
      parts = dob.split('/');
      day = Number(parts[0]);
      month = Number(parts[1]);
    }
    
    const daySum = String(day).split('').reduce((sum, d) => sum + parseInt(d), 0);
    const monthSum = String(month).split('').reduce((sum, d) => sum + parseInt(d), 0);
    const yearSum = String(year).split('').reduce((sum, d) => sum + parseInt(d), 0);
    
    const total = daySum + monthSum + yearSum;
    const sumDigits = (n: number): number => String(n).split('').reduce((acc, char) => acc + (Number(char) || 0), 0);
    const reduce = (n: number): number => (n <= 9 ? n : reduce(sumDigits(n)));
    return reduce(total);
  } catch {
    return 1;
  }
};

