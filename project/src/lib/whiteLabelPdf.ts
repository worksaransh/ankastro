// hex -> [r,g,b]
const hex = (h: string): [number, number, number] => {
  const m = (h || '').replace('#', '');
  const v = m.length === 3 ? m.split('').map((c) => c + c).join('') : m;
  const n = parseInt(v || '7c3aed', 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};

// load logo: data URL used directly, else fetched (best-effort)
const loadLogo = async (url: string): Promise<string | null> => {
  if (!url) return null;
  if (url.startsWith('data:')) return url; // uploaded logo (base64) — use as-is
  try {
    const res = await fetch(url, { mode: 'cors' });
    const blob = await res.blob();
    return await new Promise((resolve) => {
      const r = new FileReader();
      r.onloadend = () => resolve(typeof r.result === 'string' ? r.result : null);
      r.onerror = () => resolve(null);
      r.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
};

const logoFormat = (data: string): 'PNG' | 'JPEG' | 'WEBP' => {
  if (data.includes('image/jpeg') || data.includes('image/jpg')) return 'JPEG';
  if (data.includes('image/webp')) return 'WEBP';
  return 'PNG';
};

